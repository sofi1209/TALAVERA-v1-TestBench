#
# This replaces a topology in which PYRO_MATCH_N reached only K3's NC contact
# and the opto LED, both of which led back to PYRO_MATCH_P. There was no path to
# the supply return at all, so NO CURRENT COULD FLOW IN ANY STATE and the bench
