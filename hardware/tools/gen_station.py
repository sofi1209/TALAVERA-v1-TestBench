s.text("S_ESTOP: 1-2 drops bench K4 (ch 1).\n3-4 kills the ARM permit (ch 2):\nK1/K2/K3 drop, the shunt re-closes.", 62, 216, 1.3, False)

jt = s.place(CONN2, "J_TESTSW", "TEST  momentary", 45, 244)
