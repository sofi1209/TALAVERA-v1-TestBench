s.power("GND", jf['4'])
s.text("S_FIRE guarded: 1-2 and 3-4 NO, 5-6 NC aux.\nDead unless ARMED (fed from ARM_LINE).\nSKRPABE010 NOT acceptable (D-044).", 62, 186, 1.3, False)

# J_ESTOP - latching mushroom, TWO positive-opening NC blocks, two channels:
#   block 1: ESTOP_LOOP -> GND, holds bench master K4 (channel 1, as before)
#   block 2: +12V_STN -> ESTOP_OK, feeds the ARM permit (channel 2, new)
# Channel 2 removes ARM_LINE and therefore the FIRE command, so K1, K2 and K3
# all drop and the SHUNT RE-CLOSES (M-7 / B05). Before, the E-STOP dropped K4
# only and left the shunt open while ARM was on. A short of ESTOP_LOOP to the
# shield or ground defeats channel 1 silently; channel 2 still stops a burn.
