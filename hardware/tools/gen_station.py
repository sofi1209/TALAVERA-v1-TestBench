# E-STOP blocks must be positive-opening (direct opening action); the key needs
# three poles; the FIRE button needs two NO poles and one NC auxiliary.
#
# J_ARMSW - removable key, three poles:
#   pole 1 changeover: PERMIT -> ARM_LINE (ON)  or  PERMIT -> TEST_FEED (OFF)
#   pole 2, closed in OFF only: FIRE_N -> GND. TEST returns through FIRE_N, and
#           when ARMED this pole is OPEN, so FIRE_N floats unless FIRE is held.
#   pole 3, closed in OFF only: part of the RESET enable chain.
ja = s.place("Connector_Generic:Conn_01x07", "J_ARMSW", "ARM key  3-pole", 45, 160)
