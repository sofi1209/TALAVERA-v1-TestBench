s.power("GND", ja['5'])
s.text("S_ARM key: 1-2 ON / 1-3 OFF (pole 1).\n4-5 and 6-7 CLOSED IN OFF ONLY.\nARM and TEST can never both be fed.", 62, 152, 1.3, False)

# J_FIRESW - guarded momentary. Pole A ARM_LINE -> FIRE_P, pole B FIRE_N -> GND:
# the K2/K3 coils float between FIRE_P and FIRE_N, so ONE welded pole cannot
# fire and an umbilical short of either FIRE wire to ARM or ground cannot fire.
# The NC auxiliary is in the RESET chain, so a stuck FIRE actuator blocks reset.
jf = s.place("Connector_Generic:Conn_01x06", "J_FIRESW", "FIRE  2NO+1NC", 45, 193)
